package com.ermao.poc.mobireadium

import android.content.Context
import android.util.Log
import android.view.View
import android.view.ViewGroup
import android.webkit.WebView
import androidx.fragment.app.commitNow
import androidx.test.core.app.ActivityScenario
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicReference
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.readium.r2.navigator.epub.EpubNavigatorFactory
import org.readium.r2.navigator.epub.EpubNavigatorFragment
import org.readium.r2.shared.publication.Layout
import org.readium.r2.shared.publication.Link
import org.readium.r2.shared.publication.LocalizedString
import org.readium.r2.shared.publication.Manifest
import org.readium.r2.shared.publication.Metadata
import org.readium.r2.shared.publication.Publication
import org.readium.r2.shared.util.Url
import org.readium.r2.shared.util.data.Container
import org.readium.r2.shared.util.mediatype.MediaType
import org.readium.r2.shared.util.resource.InMemoryResource
import org.readium.r2.shared.util.resource.Resource

@RunWith(AndroidJUnit4::class)
@OptIn(kotlin.time.ExperimentalTime::class)
class MobiIntoEpubNavigatorInstrumentedTest {

    @Test
    fun libmobiGeneratedKf8HtmlIsActuallyRenderedByEpubNavigator() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val context = instrumentation.targetContext

        // These files are generated by libmobi's mobitool -s in the CI step immediately
        // before this instrumentation test is built. They are not hand-authored fixtures.
        val names = context.assets.list("mobi")?.toList().orEmpty().sorted()
        assertTrue("libmobi output was not packaged into the test APK", names.isNotEmpty())
        assertTrue("libmobi did not produce HTML", names.any { it.endsWith(".html") })
        assertTrue("KF8 font/CSS sample was not reconstructed", names.any { it.endsWith(".css") })
        assertTrue("KF8 embedded font was not reconstructed", names.any { it.endsWith(".otf") })

        val readingOrder = names
            .filter { it.endsWith(".html") || it.endsWith(".xhtml") }
            .map { name -> Link(Url(name)!!, mediaTypeFor(name)) }
        val otherResources = names
            .filterNot { it.endsWith(".html") || it.endsWith(".xhtml") }
            .map { name -> Link(Url(name)!!, mediaTypeFor(name)) }

        val manifest = Manifest(
            metadata = Metadata(
                conformsTo = setOf(Publication.Profile.EPUB),
                localizedTitle = LocalizedString("libmobi KF8 runtime publication"),
                layout = Layout.REFLOWABLE,
            ),
            readingOrder = readingOrder,
            resources = otherResources,
        )
        val publication = Publication(
            manifest = manifest,
            container = AssetResourceContainer(context, names),
        )
        assertTrue(publication.conformsTo(Publication.Profile.EPUB))

        val navigatorFactory = EpubNavigatorFactory(publication)
        val activityRef = AtomicReference<TestActivity>()
        val scenario = ActivityScenario.launch(TestActivity::class.java)

        try {
            scenario.onActivity { activity ->
                activityRef.set(activity)
                activity.supportFragmentManager.fragmentFactory =
                    navigatorFactory.createFragmentFactory(initialLocator = null)
                activity.supportFragmentManager.commitNow {
                    replace(android.R.id.content, EpubNavigatorFragment::class.java, null)
                }
            }

            val webView = waitForWebView(instrumentation, activityRef)
            assertNotNull("Readium EPUB Navigator never created its WebView", webView)

            val bodyText = waitForBodyText(instrumentation, webView!!)
            val currentUrl = readWebViewUrl(instrumentation, webView)
            Log.i("MobiReadiumPOC", "RENDERED_BODY=$bodyText")
            Log.i("MobiReadiumPOC", "RENDERED_URL=$currentUrl")
            assertTrue(
                "Readium WebView was created but did not render the libmobi HTML. body=$bodyText url=$currentUrl",
                bodyText != null && bodyText != "\"\"" && bodyText != "null" && bodyText.length > 4,
            )
            assertTrue(
                "Navigator did not load a publication resource URL: $currentUrl",
                !currentUrl.isNullOrBlank(),
            )
        } finally {
            scenario.close()
            publication.close()
        }
    }

    private fun waitForWebView(
        instrumentation: android.app.Instrumentation,
        activityRef: AtomicReference<TestActivity>,
    ): WebView? {
        repeat(80) {
            val result = AtomicReference<WebView?>()
            instrumentation.runOnMainSync {
                val activity = activityRef.get()
                if (activity != null) {
                    result.set(findWebView(activity.window.decorView))
                }
            }
            result.get()?.let { return it }
            Thread.sleep(100)
        }
        return null
    }

    private fun waitForBodyText(
        instrumentation: android.app.Instrumentation,
        webView: WebView,
    ): String? {
        repeat(80) {
            val result = AtomicReference<String?>()
            val latch = CountDownLatch(1)
            instrumentation.runOnMainSync {
                webView.evaluateJavascript(
                    "document.body ? document.body.innerText : ''",
                ) { value ->
                    result.set(value)
                    latch.countDown()
                }
            }
            latch.await(1, TimeUnit.SECONDS)
            val value = result.get()
            if (value != null && value != "\"\"" && value != "null" && value.length > 4) {
                return value
            }
            Thread.sleep(100)
        }
        return null
    }

    private fun readWebViewUrl(
        instrumentation: android.app.Instrumentation,
        webView: WebView,
    ): String? {
        val result = AtomicReference<String?>()
        instrumentation.runOnMainSync {
            result.set(webView.url)
        }
        return result.get()
    }

    private fun findWebView(view: View): WebView? {
        if (view is WebView) return view
        if (view is ViewGroup) {
            for (i in 0 until view.childCount) {
                findWebView(view.getChildAt(i))?.let { return it }
            }
        }
        return null
    }

    private fun mediaTypeFor(name: String): MediaType = when {
        name.endsWith(".html") -> MediaType("text/html")!!
        name.endsWith(".xhtml") -> MediaType("application/xhtml+xml")!!
        name.endsWith(".css") -> MediaType("text/css")!!
        name.endsWith(".jpg") || name.endsWith(".jpeg") -> MediaType("image/jpeg")!!
        name.endsWith(".png") -> MediaType("image/png")!!
        name.endsWith(".gif") -> MediaType("image/gif")!!
        name.endsWith(".otf") -> MediaType("font/otf")!!
        name.endsWith(".ttf") -> MediaType("font/ttf")!!
        name.endsWith(".mp3") -> MediaType("audio/mpeg")!!
        name.endsWith(".mpg") -> MediaType("video/mpeg")!!
        else -> MediaType("application/octet-stream")!!
    }

    private class AssetResourceContainer(
        private val context: Context,
        names: List<String>,
    ) : Container<Resource> {
        private val names = names.toSet()
        override val entries: Set<Url> = names.mapNotNull { Url(it) }.toSet()

        override fun get(url: Url): Resource? {
            val name = url.toString().removePrefix("./").removePrefix("/")
            if (name !in names) return null
            val bytes = context.assets.open("mobi/$name").use { it.readBytes() }
            return InMemoryResource(bytes)
        }

        override fun close() = Unit
    }
}
