package com.ermao.library.shared.modules.library.domain

data class Volume(
    val id: String,
    val mediaVersionId: String,
    val title: String,
    val volumeIndex: Double?,
    val sortOrder: Int,
    val format: String,
    val readerType: String,
    val classification: VolumeClassification,
    val readable: Boolean,
    val conversionAvailable: Boolean,
    val kindleSendAvailable: Boolean,
    val derivedFromVolumeId: String?,
    val publisher: String?,
    val publishedAt: String?,
    val language: String?,
    val isbn: String?,
    val identifier: String?,
    val narrator: String?,
    val abridged: Boolean?,
    val origin: String?,
    val importStatus: String?,
    val importError: String?,
    val coverStatus: String?,
    val coverUrl: String,
    val sizeBytes: Long,
    val pageCount: Int?,
    val chapterCount: Int?,
    val durationMillis: Long?,
    val trackCount: Int?,
    val progress: Double,
    val completed: Boolean?,
    val lastReadAt: String?,
    val files: List<VolumeFile>,
)

data class VolumeClassification(
    val source: String,
    val reason: String,
    val suggestedMediaKind: MediaKind?,
)

data class VolumeFile(
    val id: String,
    val volumeId: String?,
    val path: String,
    val mimeType: String?,
    val kind: String?,
    val sortOrder: Int?,
    val sizeBytes: Long,
    val displaySize: String,
    val durationMillis: Long?,
    val codec: String?,
    val bitrate: Int?,
    val sampleRate: Int?,
    val channels: Int?,
    val discNumber: Int?,
    val trackNumber: Int?,
    val url: String?,
)
